import unittest
from unittest.mock import Mock, patch
from urllib.parse import parse_qs, urlsplit

from lens_session import LensSession, classify, followup_url, google_url
from lens_upload import ConsentRequired

URL = 'https://lens.google.com/search?p=IMAGE_SESSION&ep=gsbubb'
SNAPSHOT = dict(url=URL, title='Google Lens', text='Results read from Lens, not generated by an AI.',
                links=[dict(title='Product', url='https://example.org/product')], complete=True, resultCount=1, answerCount=0, searchPage=True)


class LensSessionTests(unittest.TestCase):
    def test_question_is_restored_before_waiting_for_image_results(self):
        location = ['https://www.google.com/imghp?hl=it']
        window = Mock()
        window.get_current_url.side_effect = lambda: location[0]
        window.load_url.side_effect = lambda url: location.__setitem__(0, url)
        def snapshot(script):
            if '/imghp' in location[0]:
                return dict(url=location[0], complete=True, landing=True, text='')
            if parse_qs(urlsplit(location[0]).query).get('q'):
                return dict(SNAPSHOT, url=location[0])
            return dict(url=location[0], complete=True, searchPage=True, text='', resultCount=0)
        window.evaluate_js.side_effect = snapshot
        def factory(title, **options):
            location[0] = options['url']
            return window
        session = LensSession(b'image', window_factory=factory, visible=True, timeout=6)
        clock = [0]
        with patch.object(session, '_upload_in_browser', side_effect=lambda: location.__setitem__(0, URL)), \
             patch('lens_session.time.monotonic', side_effect=lambda: clock[0]), \
             patch('lens_session.time.sleep', side_effect=lambda _: clock.__setitem__(0, clock[0] + 1)):
            answer = session.query('Cos’è? & dettagli')
        self.assertEqual(answer['text'], SNAPSHOT['text'])
        self.assertEqual(parse_qs(urlsplit(location[0]).query)['q'], ['Cos’è? & dettagli'])
        self.assertEqual(parse_qs(urlsplit(location[0]).query)['p'], ['IMAGE_SESSION'])

    def test_visible_lens_uploads_in_same_window_and_stays_open_for_results(self):
        window = Mock()
        window.get_current_url.return_value = URL
        landing = dict(url='https://www.google.com/imghp', complete=True, landing=True, text='')
        window.evaluate_js.side_effect = [landing, SNAPSHOT, SNAPSHOT, SNAPSHOT, SNAPSHOT]
        uploader = Mock()
        factory = Mock(return_value=window)
        session = LensSession(b'image', window_factory=factory, uploader=uploader, visible=True)
        with patch.object(session, '_upload_in_browser') as upload, patch('lens_session.time.sleep'):
            self.assertEqual(session.query('Cos’è?')['text'], SNAPSHOT['text'])
        factory.assert_called_once()
        self.assertEqual(factory.call_args.kwargs['url'], 'https://www.google.com/imghp?hl=it')
        uploader.assert_not_called()
        upload.assert_called_once()
        window.show.assert_called()
        window.hide.assert_not_called()

    def test_repeated_consent_uses_same_window_instead_of_rejecting_request(self):
        window = Mock()
        window.get_current_url.return_value = URL
        challenge = dict(SNAPSHOT, url='https://consent.google.com/m')
        window.evaluate_js.side_effect = [challenge, SNAPSHOT, challenge, SNAPSHOT, SNAPSHOT, SNAPSHOT]
        factory = Mock(return_value=window)
        session = LensSession(b'image', window_factory=factory, uploader=Mock(return_value=URL))
        with patch('lens_session.time.sleep'):
            self.assertEqual(session.query()['text'], SNAPSHOT['text'])
        factory.assert_called_once()
        self.assertEqual(window.show.call_count, 2)

    def test_consent_window_stays_visible_while_redirect_is_loading(self):
        window = Mock()
        window.get_current_url.return_value = URL
        loading = dict(url=URL, complete=False, text='')
        snapshots = iter([dict(SNAPSHOT, url='https://consent.google.com/m'), loading,
                          loading, SNAPSHOT, SNAPSHOT, SNAPSHOT])
        current = {}
        def read(script):
            current.update(snapshot=next(snapshots))
            return current['snapshot']
        def hide():
            self.assertTrue(current['snapshot']['complete'], 'Consent window hidden during loading')
        window.evaluate_js.side_effect = read
        window.hide.side_effect = hide
        session = LensSession(b'image', window_factory=Mock(return_value=window), uploader=Mock(return_value=URL))
        with patch('lens_session.time.sleep'):
            self.assertEqual(session.query()['text'], SNAPSHOT['text'])
        window.show.assert_called_once()

    def test_hidden_reader_without_results_is_revealed_once_and_resumes(self):
        window = Mock()
        window.get_current_url.return_value = URL
        visible = [False]
        clock = [0]
        window.show.side_effect = lambda: visible.__setitem__(0, True)
        window.evaluate_js.side_effect = lambda script: SNAPSHOT if visible[0] else dict(url=URL, complete=True, text='')
        session = LensSession(b'image', window_factory=Mock(return_value=window),
                              uploader=Mock(return_value=URL), timeout=10)
        with patch('lens_session.time.monotonic', side_effect=lambda: clock[0]), \
             patch('lens_session.time.sleep', side_effect=lambda value: clock.__setitem__(0, clock[0] + 3)):
            self.assertEqual(session.query()['text'], SNAPSHOT['text'])
        window.show.assert_called_once()
        window.hide.assert_called()

    def test_followup_preserves_image_session_and_replaces_question(self):
        target = followup_url(URL + '&q=old', 'Dove si compra?')
        params = parse_qs(urlsplit(target).query)
        self.assertEqual(params['p'], ['IMAGE_SESSION'])
        self.assertEqual(params['q'], ['Dove si compra?'])
        self.assertFalse(google_url('https://www.google.com.evil.example/search'))
        with self.assertRaises(RuntimeError):
            followup_url('https://example.org/search', 'question')

    def test_results_are_read_from_isolated_webview_and_reused(self):
        window = Mock()
        window.get_current_url.return_value = URL
        window.evaluate_js.return_value = SNAPSHOT
        factory = Mock(return_value=window)
        session = LensSession(b'image bytes', window_factory=factory, uploader=Mock(return_value=URL))
        with patch('lens_session.time.sleep'):
            first = session.query('What is it?')
            second = session.query('Where to buy?')
        self.assertEqual(first, second)
        self.assertEqual(first['text'], SNAPSHOT['text'])
        self.assertEqual(first['links'], SNAPSHOT['links'])
        factory.assert_called_once()
        self.assertIsNone(factory.call_args.kwargs['js_api'])
        self.assertTrue(factory.call_args.kwargs['hidden'])
        self.assertEqual(parse_qs(urlsplit(window.load_url.call_args.args[0]).query)['p'], ['IMAGE_SESSION'])
        session.uploader.assert_called_once_with(b'image bytes')

    def test_verification_uses_same_window_then_resumes_results(self):
        window = Mock()
        window.get_current_url.return_value = URL
        window.evaluate_js.side_effect = [dict(SNAPSHOT, url='https://consent.google.com/m'), SNAPSHOT, SNAPSHOT, SNAPSHOT]
        factory = Mock(return_value=window)
        session = LensSession(b'image', window_factory=factory, uploader=Mock(return_value=URL))
        with patch('lens_session.time.sleep'):
            self.assertEqual(session.query()['text'], SNAPSHOT['text'])
        factory.assert_called_once()
        window.show.assert_called_once()
        self.assertGreaterEqual(window.hide.call_count, 1)

    def test_direct_consent_reuploads_image_in_authorized_window(self):
        window = Mock()
        window.get_current_url.return_value = URL
        challenge = dict(SNAPSHOT, url='https://consent.google.com/m')
        landing = dict(url='https://www.google.com/imghp', title='Google', text='', links=[], complete=True, landing=True)
        window.evaluate_js.side_effect = [challenge, landing, landing, SNAPSHOT, SNAPSHOT, SNAPSHOT, SNAPSHOT]
        uploader = Mock(side_effect=ConsentRequired('https://consent.google.com/m'))
        factory = Mock(return_value=window)
        session = LensSession(b'image', window_factory=factory, uploader=uploader)
        with patch.object(session, '_upload_in_browser') as submit, patch('lens_session.time.sleep'):
            self.assertEqual(session.query('Qual è il prodotto?')['text'], SNAPSHOT['text'])
        factory.assert_called_once()
        window.show.assert_called_once()
        submit.assert_called_once()
        uploader.assert_called_once()
        self.assertEqual(parse_qs(urlsplit(window.load_url.call_args.args[0]).query)['q'], ['Qual è il prodotto?'])

    def test_existing_webview_consent_does_not_show_another_window(self):
        window = Mock()
